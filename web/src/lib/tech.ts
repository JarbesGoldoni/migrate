export function batchIcon(name?: string): LucideIcon {
  if (!name) return Layers
  const key = name
    .trim()
    .replace(/Icon$/, "")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase()
  return BATCH_ICONS[key] ?? BATCH_ICONS[key.split("-")[0]] ?? Layers
}

