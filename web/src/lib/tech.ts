const LOOKUP = new Map<string, BrandIcon>(BRANDS.flatMap(([names, icon]) => names.map((n) => [n, icon] as const)))

export function brandIcon(tech?: string): BrandIcon | undefined {
  if (!tech) return undefined
  const key = tech.toLowerCase().trim()
  const direct = LOOKUP.get(key)
  if (direct) return direct
  const tokens = key.split(/[^a-z0-9.#+/]+/).filter(Boolean)
  for (const token of tokens) {
    const hit = LOOKUP.get(token) ?? LOOKUP.get(token.replace(/[0-9.]+$/, ""))
    if (hit) return hit
  }
  return undefined
}

/** Brand colors are designed for white pages; lift the dark ones so they read on ink. */
export function readableHex(hex: string) {
  const n = Number.parseInt(hex, 16)
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255]
  const luminance = (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255
  return luminance < 0.28 ? "#d5dbe7" : `#${hex}`
}

